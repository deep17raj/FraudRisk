"""The single miner.yaml must satisfy Telegraph's closed schema and match every registered intent.

Registration is rejected outright on any unknown key, so these tests are the cheap way to
find that out before spending a bond on a failing transaction. The expectations come from
`telegraphintent/registry.py`; the file itself is generated by scripts/sync_intents.py.
"""
from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "scripts"))

import sync_intents  # noqa: E402

from telegraphintent.registry import IDENTITY, INTENTS  # noqa: E402

RAW = (ROOT / "miner.yaml").read_bytes()
DOC = yaml.safe_load(RAW)

TOP = {"version", "kind", "id", "slug", "protocol", "name", "description", "base_url",
       "input_schema", "output_schema", "intent_mapping", "polling", "cache_ttl_sec",
       "rate_limit_per_sec", "circuit_threshold", "circuit_cooldown_seconds", "docs",
       "limitations", "errors", "auth", "endpoints", "semantics"}
ENDPOINT = {"path", "external_path", "method", "description", "intents", "params",
            "endpoint_base_url", "content_type", "multipart_fields", "param_map"}
AUTH = {"type", "env_var", "header_name", "value_prefix", "inject"}
SIGNAL = {"confidence_field", "label_field", "reason_field"}
SEMANTICS = {"signal_mapping", "supported_intents"}
PARAM = {"name", "type", "intents", "description", "accepted_fields"}
REQUIRED = {"version", "kind", "id", "slug", "name", "base_url"}
PARAM_TYPES = {"string", "integer", "number"}


def test_no_unknown_keys_anywhere():
    assert set(DOC) <= TOP, set(DOC) - TOP
    assert REQUIRED <= set(DOC)
    assert set(DOC["auth"]) <= AUTH and DOC["auth"]["type"] in {"bearer", "header", "none"}
    assert set(DOC["semantics"]) <= SEMANTICS
    assert set(DOC["semantics"].get("signal_mapping", {})) <= SIGNAL
    for ep in DOC["endpoints"]:
        assert set(ep) <= ENDPOINT, set(ep) - ENDPOINT
        assert "input_schema" not in ep and "output_schema" not in ep


def test_identity_fields():
    assert DOC["version"] == "1" and DOC["kind"] == "miner"
    assert DOC["protocol"] in {"generic", "bittensor"}
    assert isinstance(DOC["id"], int) and DOC["id"] > 0
    assert re.fullmatch(r"[a-z0-9]+(-[a-z0-9]+)*", DOC["slug"])
    assert DOC["base_url"].startswith(("http://", "https://"))
    assert DOC["description"].strip() and DOC["name"].strip()


def test_the_miners_identity_has_not_changed():
    """Rule A1: a new id or slug is a new miner on the leaderboard."""
    for key, value in IDENTITY.items():
        assert DOC[key] == value, f"{key} changed: {DOC[key]!r} != {value!r}"


def test_one_endpoint_per_intent_with_the_right_request_fields():
    eps = {ep["path"]: ep for ep in DOC["endpoints"]}
    assert set(eps) == {s.path for s in INTENTS}, "miner.yaml must declare exactly the registered endpoints"
    assert len(DOC["endpoints"]) == len(INTENTS)
    for spec in INTENTS:
        ep = eps[spec.path]
        assert ep["external_path"] == spec.path and ep["method"] == "POST"
        assert ep["description"].strip() and ep["intents"] == [spec.intent]
        body = ep["params"]["body"]
        assert set(body) <= {"required", "optional"}
        got = {"required": body.get("required", []), "optional": body.get("optional", [])}
        assert tuple(p["name"] for p in got["required"]) == tuple(p.name for p in spec.params if p.required)
        assert tuple(p["name"] for p in got["optional"]) == tuple(p.name for p in spec.params if not p.required)
        want = {p.name: p for p in spec.params}
        for p in got["required"] + got["optional"]:
            assert p["type"] in PARAM_TYPES and p["type"] == want[p["name"]].type
            assert p["intents"] == ["*"] and p["description"]
            assert set(p) <= PARAM, set(p) - PARAM


def test_supported_intents_are_consistent():
    supported = set(DOC["semantics"]["supported_intents"])
    assert supported == {s.intent for s in INTENTS}
    assert len(DOC["semantics"]["supported_intents"]) == len(INTENTS)
    assert all(set(ep["intents"]) <= supported for ep in DOC["endpoints"])


def test_signal_mapping_if_present_names_real_fields():
    sm = DOC["semantics"].get("signal_mapping")
    if not sm:
        return
    shared = set.intersection(*(set(s.fields) for s in INTENTS))
    for key, value in sm.items():
        assert value in shared, f"{key}={value} is not returned by every intent"


def test_file_is_lf_only_and_utf8():
    """The on-chain sha256 must match the bytes served at YAML_URL byte for byte."""
    assert b"\r" not in RAW
    assert not RAW.startswith(b"\xef\xbb\xbf"), "a UTF-8 BOM would change the hash"
    RAW.decode("utf-8")


def test_miner_yaml_is_exactly_what_the_registry_generates():
    """Rule F18: the YAML is generated. Run `python scripts/sync_intents.py` instead of editing it."""
    assert RAW.decode("utf-8") == sync_intents.render_yaml(), "miner.yaml is stale: run scripts/sync_intents.py"


def test_generated_blocks_of_register_and_dockerfile_are_current():
    for path, text in sync_intents.expected_files().items():
        assert path.read_bytes().decode("utf-8") == text, f"{path.name} is stale: run scripts/sync_intents.py"


def test_register_script_covers_every_intent():
    script = (ROOT / "register.sh").read_text(encoding="utf-8")
    assert "REPLACE-WITH" in script, "the guard that blocks a placeholder base_url is missing"
    for spec in INTENTS:
        assert spec.intent in script
        assert f"probe {spec.path} " in script, f"register.sh does not smoke-test {spec.path}"
    assert "sha256" in script.lower()
    for secret in ("MINER_PRIVATE_KEY=0x", "0x1234"):
        assert f"\n{secret}" not in script, "no real or dummy key may be hardcoded"


def test_dockerfile_ships_every_package():
    docker = (ROOT / "Dockerfile").read_text(encoding="utf-8")
    for pkg in ("telegraphintent", "intentkit", *{s.package.split(".")[0] for s in INTENTS}):
        assert f"COPY {pkg} ./{pkg}" in docker
    assert "COPY miner.yaml" in docker and "telegraphintent.app:app" in docker


def test_the_hash_of_the_served_file_is_stable():
    assert hashlib.sha256(RAW).hexdigest() == hashlib.sha256((ROOT / "miner.yaml").read_bytes()).hexdigest()
